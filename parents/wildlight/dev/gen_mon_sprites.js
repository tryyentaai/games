// Generates js/sprites_mons.js from part-based creature definitions (dev/mon_defs.js).
// Shapes are rasterized with per-part lighting (top-left light), dithered shade bands, highlights,
// outer + inner dark outlines, then hand-placed pixel details are stamped on top.
// Back sprites: mirrored, enlarged 1.15x from the bottom (over-the-shoulder), face details removed.
// Icons: 0.5x render with re-outlining + eye dots.   Run: node dev/gen_mon_sprites.js [--png out.png]
'use strict';
const fs = require('fs'), path = require('path'), zlib = require('zlib');
const DEFS = require('./mon_defs.js');

function inside(p, X, Y) {
  if (p.t === 'e') {
    const a = ((p.rot || 0) * Math.PI) / 180, dx = X - p.x, dy = Y - p.y;
    const u = dx * Math.cos(a) + dy * Math.sin(a), v = -dx * Math.sin(a) + dy * Math.cos(a);
    const nx = u / p.rx, ny = v / p.ry;
    return nx * nx + ny * ny <= 1 ? [nx, ny] : null;
  }
  // polygon (even-odd)
  const pts = p.pts; let c = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i], [xj, yj] = pts[j];
    if ((yi > Y) !== (yj > Y) && X < ((xj - xi) * (Y - yi)) / (yj - yi) + xi) c = !c;
  }
  if (!c) return null;
  if (!p._bb) { const xs = pts.map((q) => q[0]), ys = pts.map((q) => q[1]); p._bb = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)]; }
  const [x0, x1, y0, y1] = p._bb;
  return [((X - x0) / Math.max(1, x1 - x0)) * 2 - 1, ((Y - y0) / Math.max(1, y1 - y0)) * 2 - 1];
}

// view: {size, scale, mirror, back}
function render(def, view) {
  const N = view.size, s = view.scale;
  const id = Array.from({ length: N }, () => new Array(N).fill(-1));
  const col = Array.from({ length: N }, () => new Array(N).fill(-1));
  let parts = def.parts.filter((p) => (view.back ? !p.front : !p.back));
  if (view.back) parts = parts.filter((p) => !p.tail).concat(parts.filter((p) => p.tail));
  const ax = 16, ay = 31; // anchor for back zoom
  parts.forEach((p, pi) => {
    for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
      let X = (x + 0.5) / s, Y = (y + 0.5) / s;
      if (view.zoom) { X = (X - ax) / view.zoom + ax; Y = (Y - ay) / view.zoom + ay; }
      if (view.mirror) X = 32 - X;
      const n = inside(p, X, Y); if (!n) continue;
      let [nx, ny] = n; if (view.mirror) nx = -nx;
      const c = p.c;
      let v = c;
      if (!p.flat) {
        const d = (p.lx == null ? 0.5 : p.lx) * nx + (p.ly == null ? 0.8 : p.ly) * ny;
        const sh = Math.min(3, c + 1);
        if (d > 0.5) v = sh;
        else if (d > 0.3 && ((x + y) & 1)) v = sh;
        else if (d < -0.62 && c > 0 && p.hi !== false) v = c - 1;
      }
      id[y][x] = pi; col[y][x] = v;
    }
  });
  const out = col.map((r) => r.slice());
  const grp = (pi) => (parts[pi].g != null ? parts[pi].g : 'p' + pi);
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
    const nb = [[x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1]];
    if (id[y][x] < 0) {
      if (nb.some(([a, b]) => a >= 0 && b >= 0 && a < N && b < N && id[b][a] >= 0)) out[y][x] = 3;
    } else if (parts[id[y][x]].line !== false) {
      const me = id[y][x];
      if (nb.some(([a, b]) => a >= 0 && b >= 0 && a < N && b < N && id[b][a] > me && grp(id[b][a]) !== grp(me) && parts[id[b][a]].line !== false)) out[y][x] = 3;
    }
  }
  // details
  const dets = (def.details || []).filter((d) => (view.back ? d.back : !d.backOnly && !view.icon));
  for (const d of dets) {
    d.rows.forEach((row, j) => [...row].forEach((ch, i) => {
      if (ch === '.') return;
      let x = d.x + i, y = d.y + j;
      if (view.back) { if (view.mirror) x = 31 - x; x = Math.round((x + 0.5 - ax) * view.zoom + ax - 0.5); y = Math.round((y + 0.5 - ay) * view.zoom + ay - 0.5); }
      if (x >= 0 && y >= 0 && x < N && y < N) out[y][x] = +ch;
    }));
  }
  if (view.icon) for (const [ex, ey] of def.eyes || []) { const x = Math.floor(ex * s), y = Math.floor(ey * s); if (out[y] && out[y][x] != null) out[y][x] = 3; }
  return out.map((r) => r.map((v) => (v < 0 ? '.' : String(v))).join(''));
}

const result = {};
for (const [k, def] of Object.entries(DEFS)) {
  if (k.startsWith('__')) continue;
  result[k] = {
    front: render(def, { size: 32, scale: 1 }),
    back: render(def, { size: 32, scale: 1, mirror: true, back: true, zoom: def.backZoom || 1.08 }),
    icon: render(def, { size: 16, scale: 0.5, icon: true }),
  };
}
let js = '// WILDLIGHT — creature sprites (generated by dev/gen_mon_sprites.js from dev/mon_defs.js; hand-tuned part art).\n';
js += "// G.SPR.mons[id] = {front: 32x32 rows, back: 32x32 rows, icon: 16x16 rows}. '0'..'3' palette index, '.' transparent.\n";
js += '(function () {\n  const G = window.G; G.SPR = G.SPR || {};\n  G.SPR.mons = {\n';
for (const [k, v] of Object.entries(result)) {
  js += '    ' + k + ': {\n';
  for (const f of ['front', 'back', 'icon']) js += '      ' + f + ': [\n' + v[f].map((r) => "        '" + r + "',").join('\n') + '\n      ],\n';
  js += '    },\n';
}
js += '  };\n';
const extra = {};
for (const [k, def] of Object.entries(DEFS.__extra)) extra[k] = render(def, { size: 32, scale: 1 });
js += '  // Battle-scene extras: player back sprite + generic trainer silhouette (32x32).\n  G.SPR.battle = {\n';
for (const [k, rows] of Object.entries(extra)) js += '    ' + k + ': [\n' + rows.map((r) => "      '" + r + "',").join('\n') + '\n    ],\n';
js += '  };\n})();\n';
fs.writeFileSync(path.join(__dirname, '../js/sprites_mons.js'), js);
console.log('wrote js/sprites_mons.js', Object.keys(result).length, 'mons');

// ---------- PNG preview sheet ----------
const pi = process.argv.indexOf('--png');
if (pi > 0) {
  const PAL = [[255, 244, 207], [240, 191, 72], [176, 90, 42], [51, 24, 14]], BG = [120, 160, 200];
  const only = process.argv[pi + 2] ? process.argv[pi + 2].split(',') : null;
  const keys = Object.keys(result).filter((k) => !only || only.includes(k)).concat(only ? [] : ['__player', '__trainer']);
  const S = 4, cellW = (32 + 32 + 16 + 6) * S, cellH = 34 * S, cols = 3;
  const rowsN = Math.ceil(keys.length / cols), W = cellW * cols, H = cellH * rowsN;
  const img = Buffer.alloc(W * H * 3);
  for (let i = 0; i < W * H; i++) { img[i * 3] = BG[0]; img[i * 3 + 1] = BG[1]; img[i * 3 + 2] = BG[2]; }
  const blit = (rows, ox, oy) => rows.forEach((r, y) => [...r].forEach((ch, x) => {
    if (ch === '.') return; const c = PAL[+ch];
    for (let dy = 0; dy < S; dy++) for (let dx = 0; dx < S; dx++) { const o = ((oy + y * S + dy) * W + ox + x * S + dx) * 3; img[o] = c[0]; img[o + 1] = c[1]; img[o + 2] = c[2]; }
  }));
  keys.forEach((k, i) => {
    const ox = (i % cols) * cellW, oy = Math.floor(i / cols) * cellH + S;
    if (k === '__player') return blit(extra.player, ox, oy);
    if (k === '__trainer') return blit(extra.trainer, ox, oy);
    blit(result[k].front, ox, oy); blit(result[k].back, ox + 33 * S, oy); blit(result[k].icon, ox + 66 * S, oy);
  });
  const raw = Buffer.alloc((W * 3 + 1) * H);
  for (let y = 0; y < H; y++) { raw[y * (W * 3 + 1)] = 0; img.copy(raw, y * (W * 3 + 1) + 1, y * W * 3, (y + 1) * W * 3); }
  const crcT = []; for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; crcT[n] = c >>> 0; }
  const crc = (b) => { let c = 0xffffffff; for (const x of b) c = crcT[(c ^ x) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (t, d) => { const l = Buffer.alloc(4); l.writeUInt32BE(d.length); const td = Buffer.concat([Buffer.from(t), d]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4); ihdr[8] = 8; ihdr[9] = 2;
  fs.writeFileSync(process.argv[pi + 1], Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]));
  console.log('preview', process.argv[pi + 1]);
}
